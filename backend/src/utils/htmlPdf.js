'use strict';

// F4: Arabic-capable PDF export. Decision (docs/i18n/PDF_SPIKE.md): PDFKit's standard-font layout cannot shape or
// order Arabic, so an Arabic document is laid out as HTML and printed by headless Chromium, with the bundled IBM Plex
// Sans / Plex Sans Arabic fonts (OFL, docs/THIRD_PARTY_FONTS.md) embedded as data URLs - no runtime font or network
// request, no paid service. English documents keep the existing PDFKit layout. One spec shape feeds both renderers:
// the one `renderDocument(spec)` of utils/procurementPdf.js picks the engine, so every PDF call site (procurement,
// QC, HSE, handover, document control, reports) gets Arabic support without changing.

const fs = require('fs');
const path = require('path');
const { svcError } = require('./serviceErrors');

const FONT_DIR = path.join(__dirname, '../../assets/fonts');
const ARABIC_RANGE = /[؀-ۿݐ-ݿࢠ-ࣿﭐ-﷿ﹰ-﻿]/;

const LABELS = {
  en: { date: 'Date', page: 'Page', footer: 'System-generated by the Construction ERP.' },
  ar: { date: 'التاريخ', page: 'صفحة', footer: 'وثيقة صادرة آليًا من نظام إدارة المقاولات.' },
};

function* strings(value) {
  if (value == null) return;
  if (Array.isArray(value)) { for (const item of value) yield* strings(item); return; }
  if (value instanceof Date) return;
  if (typeof value === 'object') { for (const item of Object.values(value)) yield* strings(item); return; }
  yield String(value);
}

const specHasArabic = (spec) => {
  for (const text of strings([spec.docType, spec.brand, spec.number, spec.meta, spec.columns, spec.rows, spec.summary, spec.notes])) {
    if (ARABIC_RANGE.test(text)) return true;
  }
  return false;
};

// 'ar' when the caller asks for it or any text in the spec is Arabic; otherwise 'en'.
function resolveLocale(spec = {}) {
  if (spec.locale === 'ar' || spec.locale === 'en') return spec.locale;
  return specHasArabic(spec) ? 'ar' : 'en';
}

const esc = (value) => String(value == null ? '' : value)
  .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

// Identifiers, codes and plain numbers stay left-to-right inside right-to-left text.
const LTR_TOKEN = /^[A-Za-z0-9][A-Za-z0-9/_.:-]*$/;
const isolate = (value) => (LTR_TOKEN.test(String(value)) ? `<bdi dir="ltr">${esc(value)}</bdi>` : esc(value));

let fontCss;
function fonts() {
  if (fontCss) return fontCss;
  const face = (family, file, weight) => `@font-face{font-family:'${family}';font-weight:${weight};src:url(data:font/woff2;base64,${
    fs.readFileSync(path.join(FONT_DIR, file)).toString('base64')}) format('woff2')}`;
  fontCss = [
    face('PlexLatin', 'ibm-plex-sans-latin-400-normal.woff2', 400), face('PlexLatin', 'ibm-plex-sans-latin-700-normal.woff2', 700),
    face('PlexArabic', 'ibm-plex-sans-arabic-arabic-400-normal.woff2', 400), face('PlexArabic', 'ibm-plex-sans-arabic-arabic-700-normal.woff2', 700),
  ].join('');
  return fontCss;
}

function formatCell(raw, numberFormat) {
  if (raw == null) return '';
  if (typeof raw === 'boolean') return raw ? 'Yes' : 'No';
  if (typeof raw === 'number' || (typeof raw === 'string' && /^-?\d+(\.\d+)?$/.test(raw))) {
    const n = Number(raw);
    return Number.isFinite(n) ? numberFormat.format(n) : String(raw);
  }
  return String(raw);
}

// Columns may be {key,label,align,width} objects (procurement shape) or plain header strings with array rows (reports).
function normaliseTable(spec) {
  const columns = (spec.columns || []).map((col, index) => (typeof col === 'string' ? { key: index, label: col } : { key: col.key, label: col.label, align: col.align }));
  return { columns, rows: spec.rows || [] };
}

function buildHtml(spec, locale) {
  const rtl = locale === 'ar';
  const labels = LABELS[locale];
  const numberFormat = new Intl.NumberFormat(rtl ? 'ar-EG' : 'en-US', { maximumFractionDigits: 3 });
  const moneyFormat = new Intl.NumberFormat(rtl ? 'ar-EG' : 'en-US', { minimumFractionDigits: 2, maximumFractionDigits: 2 });
  const { columns, rows } = normaliseTable(spec);
  const brand = spec.brand || process.env.COMPANY_NAME || 'Osiris Labs';
  const date = spec.date ? (typeof spec.date === 'string' ? spec.date : new Date(spec.date).toISOString().slice(0, 10)) : '';
  // 'start'/'end' follow the writing direction; an explicit left/right from the LTR spec is mirrored.
  const alignOf = (col) => (col.align === 'right' ? 'end' : col.align === 'center' ? 'center' : 'start');

  const meta = (spec.meta || []).filter(([, v]) => v != null)
    .map(([k, v]) => `<div class="meta-row"><span class="k">${esc(k)}</span><span class="v">${isolate(v)}</span></div>`).join('');
  const head = columns.map((c) => `<th style="text-align:${alignOf(c)}">${esc(c.label)}</th>`).join('');
  const body = rows.map((row) => `<tr>${columns.map((c) => `<td style="text-align:${alignOf(c)}">${isolate(formatCell(row[c.key], numberFormat))}</td>`).join('')}</tr>`).join('');
  const summary = (spec.summary || []).filter(([, v]) => v != null)
    .map(([k, v]) => `<div class="sum-row"><span class="k">${esc(k)}</span><span class="v">${isolate(typeof v === 'number' ? moneyFormat.format(v) : v)}</span></div>`).join('');

  return `<!doctype html><html lang="${locale}" dir="${rtl ? 'rtl' : 'ltr'}"><head><meta charset="utf-8"><style>${fonts()}
  @page{size:A4;margin:14mm 12mm 18mm}
  *{box-sizing:border-box}
  body{margin:0;color:#1d2732;font:10.5pt/1.5 ${rtl ? "'PlexArabic','PlexLatin'" : "'PlexLatin','PlexArabic'"},sans-serif}
  .band{background:#1a3c5e;color:#fff;padding:14px 18px;margin-bottom:16px}
  .band .brand{font-size:15pt;font-weight:700}.band .sub{font-size:9pt;opacity:.9}
  h1{font-size:14pt;color:#1a3c5e;margin:0 0 4px}.date{color:#555;font-size:9pt;margin-bottom:10px}
  .meta{border-top:1px solid #ccc;padding-top:8px;margin-bottom:10px}
  .meta-row{display:flex;gap:8px;font-size:9.5pt;margin-bottom:2px}.meta-row .k{font-weight:700;color:#333;min-width:34%}
  table{width:100%;border-collapse:collapse;margin-top:8px;font-size:9.5pt}
  thead{display:table-header-group}th{color:#1a3c5e;border-bottom:1.5px solid #1a3c5e;padding:5px 4px;font-weight:700}
  td{padding:4px;border-bottom:1px solid #e4e8ec;vertical-align:top}tr{break-inside:avoid}
  .sum{margin-top:12px;border-top:1px solid #ccc;padding-top:8px;max-width:60%;margin-inline-start:auto}
  .sum-row{display:flex;justify-content:space-between;gap:12px;font-size:10.5pt;margin-bottom:3px}.sum-row .k{font-weight:700;color:#333}
  .notes{margin-top:14px;color:#555;font-size:9pt;font-style:italic;white-space:pre-wrap}
  </style></head><body>
  <header class="band"><div class="brand">${esc(brand)}</div><div class="sub">${esc(spec.docType || '')}${spec.number ? ' · ' : ''}${spec.number ? `<bdi dir="ltr">${esc(spec.number)}</bdi>` : ''}</div></header>
  <h1>${esc(spec.docType || '')}</h1>${date ? `<div class="date">${esc(labels.date)}: <bdi dir="ltr">${esc(date)}</bdi></div>` : ''}
  ${meta ? `<section class="meta">${meta}</section>` : ''}
  ${columns.length ? `<table><thead><tr>${head}</tr></thead><tbody>${body}</tbody></table>` : ''}
  ${summary ? `<section class="sum">${summary}</section>` : ''}
  ${spec.notes ? `<div class="notes">${esc(spec.notes)}</div>` : ''}
  </body></html>`;
}

let browserPromise = null;
let idleTimer = null;

async function getBrowser() {
  if (!browserPromise) {
    browserPromise = (async () => {
      const { chromium } = require('playwright-core');
      return chromium.launch({
        headless: true,
        executablePath: process.env.PDF_CHROMIUM_PATH || undefined,
        args: ['--no-sandbox', '--disable-dev-shm-usage', '--disable-gpu', '--font-render-hinting=none'],
      });
    })();
    browserPromise.catch(() => { browserPromise = null; });
  }
  const browser = await browserPromise;
  clearTimeout(idleTimer);
  idleTimer = setTimeout(closeBrowser, 30000);
  if (idleTimer.unref) idleTimer.unref();
  return browser;
}

async function closeBrowser() {
  clearTimeout(idleTimer);
  const pending = browserPromise;
  browserPromise = null;
  if (pending) { try { await (await pending).close(); } catch (_) { /* already gone */ } }
}

// spec -> Promise<Buffer>. Arabic output is never produced by PDFKit: if Chromium cannot start this fails loudly
// rather than returning a document with corrupted Arabic text.
async function renderHtmlPdf(spec, { locale = resolveLocale(spec) } = {}) {
  let browser;
  try {
    browser = await getBrowser();
  } catch (error) {
    console.error('[pdf] Chromium unavailable for Arabic PDF export:', error.message);
    throw svcError(503, 'pdf_renderer_unavailable', 'The PDF renderer is not available');
  }
  const page = await browser.newPage();
  try {
    await page.setContent(buildHtml(spec, locale), { waitUntil: 'load' });
    await page.evaluate(() => document.fonts.ready);
    const footer = `<div style="width:100%;font-size:8px;color:#888;text-align:center;font-family:sans-serif"><span>${esc(spec.number || '')}</span> — <span class="pageNumber"></span> / <span class="totalPages"></span></div>`;
    const buffer = await page.pdf({
      format: 'A4', printBackground: true, displayHeaderFooter: true,
      headerTemplate: '<span></span>', footerTemplate: footer,
      margin: { top: '14mm', right: '12mm', bottom: '18mm', left: '12mm' },
      tagged: false,
    });
    return Buffer.from(buffer);
  } finally {
    await page.close().catch(() => {});
  }
}

module.exports = { resolveLocale, specHasArabic, buildHtml, renderHtmlPdf, closeBrowser };
